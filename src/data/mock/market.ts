export async function getListing(id: string): Promise<Listing | undefined> {
  const listings = await getListings();
  return listings.find((l) => l.id === id);
}

export async function getListingsByCategory(cat: Listing["category"]): Promise<Listing[]> {
  const listings = await getListings();
  return listings.filter((l) => l.category === cat);
}

export async function getVerifiedBikes(): Promise<Listing[]> {
  const listings = await getListings();
  return listings.filter((l) => l.category === "bike" && l.isVerified);
}

export async function getUnverifiedBikes(): Promise<Listing[]> {
  const listings = await getListings();
  return listings.filter((l) => l.category === "bike" && !l.isVerified);
}
